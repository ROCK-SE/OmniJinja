/**
 * Triggers the Python parsing script asynchronously for queued .py files.
 */
async function processQueue(enginePath: string, workspaceRoot: string) {
    if (isParsing || parseQueue.length === 0) return;
    isParsing = true;

    while (parseQueue.length > 0) {
        const filePath = parseQueue.shift()!; 
        const scriptPath = path.join(enginePath, 'main_py_parser.py');
        const command = `${activePythonCmd} "${scriptPath}" "${filePath}" "${workspaceRoot}"`;

        const doc = vscode.workspace.textDocuments.find(d => d.uri.fsPath === filePath);
        const content = doc ? doc.getText() : fs.readFileSync(filePath, 'utf-8');

        try {
            await new Promise((resolve, reject) => {
                const child = exec(command, (error, stdout) => {
                    if (error) reject(error);
                    else resolve(stdout);
                });
                if (child.stdin) {
                    child.stdin.write(content);
                    child.stdin.end();
                }
            });
            loadSchemaIntoMemory(filePath, workspaceRoot);
        } catch (e) {
            console.error(`Python Backend Parsing Error: ${filePath}`, e);
        }
    }
    isParsing = false; 
}

/**
 * Triggers the Jinja syntax detection script asynchronously for queued templates.
 */
async function processJinjaQueue(enginePath: string, workspaceRoot: string) {
    if (isJinjaParsing || jinjaParseQueue.length === 0) return;
    isJinjaParsing = true;

    while (jinjaParseQueue.length > 0) {
        const filePath = jinjaParseQueue.shift()!; 
        const scriptPath = path.join(enginePath, 'main_jinja_parser.py');
        const command = `${activePythonCmd} "${scriptPath}" "${filePath}" "${workspaceRoot}"`;
        const doc = vscode.workspace.textDocuments.find(d => d.uri.fsPath === filePath);
        const content = doc ? doc.getText() : fs.readFileSync(filePath, 'utf-8');

        try {
            await new Promise((resolve, reject) => {
                const child = exec(command, (error, stdout) => {
                    if (error) reject(error);
                    else resolve(stdout);
                });
                if (child.stdin) {
                    child.stdin.write(content);
                    child.stdin.end();
                }
            });
            loadJinjaSchemaIntoMemory(filePath, workspaceRoot);
        } catch (e) {
            console.error(`Jinja Syntax Parsing Error: ${filePath}`, e);
        }
    }
    isJinjaParsing = false; 
}

/**
 * Reads the generated _schema.json file and updates the in-memory registries.
 */
function loadSchemaIntoMemory(pyFilePath: string, workspaceRoot: string) {
    const baseName = path.basename(pyFilePath);
    const safeName = baseName + "_schema.json";
    const jsonPath = path.join(workspaceRoot, 'output_schemas', safeName);

    if (!fs.existsSync(jsonPath)) return;

    try {
        const schemaData = JSON.parse(fs.readFileSync(jsonPath, 'utf-8'));
        
        if (schemaData.render_calls) {
            // Save raw calls for data flow validation
            renderCallRegistry.set(pyFilePath, schemaData.render_calls);

            for (const call of schemaData.render_calls) {
                const templateName = path.basename(call.template);
                if (!templateRegistry.has(templateName)) {
                    templateRegistry.set(templateName, new Map<string, any>());
                }
                templateRegistry.get(templateName)!.set(pyFilePath, call.context);
            }

            // TRIGGER VALIDATION: Python changed, re-validate supply against existing demand
            validateDataFlow(pyFilePath);
        } else {
            renderCallRegistry.delete(pyFilePath);
            pyDiagnosticCollection.delete(vscode.Uri.file(pyFilePath));
        }

        if (schemaData.custom_filters && schemaData.custom_filters.length > 0) {
            filterRegistry.set(pyFilePath, schemaData.custom_filters);
        } else {
            filterRegistry.delete(pyFilePath);
        }

        if (schemaData.template_files && Array.isArray(schemaData.template_files) && schemaData.template_files.length > 0) {
            templateFilesRegistry.set(pyFilePath, new Set(schemaData.template_files));
        } else {
            templateFilesRegistry.delete(pyFilePath);
        }

    } catch (e) {
        console.error("Failed to load backend JSON schema", e);
    }
}

/**
 * Reads the generated _jinja.json file, applies wavy underline diagnostics, 
 * and caches the repaired code for Quick Fixes.
 */
function loadJinjaSchemaIntoMemory(htmlFilePath: string, workspaceRoot: string) {
    const baseName = path.basename(htmlFilePath);
    const safeName = baseName + "_jinja.json"; 
    const jsonPath = path.join(workspaceRoot, 'jinja_schemas', safeName);

    if (!fs.existsSync(jsonPath)) {
        diagnosticCollection.delete(vscode.Uri.file(htmlFilePath));
        return;
    }

    try {
        const data = JSON.parse(fs.readFileSync(jsonPath, 'utf-8'));
        
        const internalData = {};
        if (data.internal_variables) {
            Object.assign(internalData, data.internal_variables);
        }
        if (data.macros) {
            Object.assign(internalData, data.macros);
        }
        
        internalJinjaRegistry.set(baseName, internalData);

        if (data.fixed_code) {
            fixedCodeRegistry.set(htmlFilePath, data.fixed_code);
        } else {
            fixedCodeRegistry.delete(htmlFilePath);
        }

        // Extract and store External Requirements (Demand)
        if (data.external_requirements) {
            externalRequirementsRegistry.set(baseName, data.external_requirements);
            
            // TRIGGER VALIDATION: HTML changed, re-validate all Python files that supply this template
            const pySourcesMap = templateRegistry.get(baseName);
            if (pySourcesMap) {
                for (const pyPath of pySourcesMap.keys()) {
                    validateDataFlow(pyPath);
                }
            }
        } else {
            externalRequirementsRegistry.delete(baseName);
        }

        if (data.diagnostics && Array.isArray(data.diagnostics)) {
            const diagnostics: vscode.Diagnostic[] = [];
            
            // Check if this HTML template is rendered by any known Python file
            const isLinked = templateRegistry.has(baseName) && templateRegistry.get(baseName)!.size > 0;

            for (const diag of data.diagnostics) {
                // Suppress "Undefined" warnings if the template is not linked to any Python backend yet
                const isUndefinedWarning = diag.message && diag.message.toLowerCase().includes('undefined');
                if (!isLinked && isUndefinedWarning) {
                    continue; // Skip pushing this diagnostic
                }

                const lineNum = Math.max(0, (diag.line || 1) - 1);
                
                let colNum = 0;
                let length = 1000; 
                
                if (diag.col) {
                    colNum = Math.max(0, diag.col - 1);
                    length = diag.original ? String(diag.original).length : 5;
                }
                
                const range = new vscode.Range(lineNum, colNum, lineNum, colNum + length);
                const severity = diag.severity === 'error' ? vscode.DiagnosticSeverity.Error : vscode.DiagnosticSeverity.Warning;
                
                const diagnostic = new vscode.Diagnostic(range, diag.message, severity);
                diagnostic.source = 'OmniJinja';
                diagnostics.push(diagnostic);
            }
            diagnosticCollection.set(vscode.Uri.file(htmlFilePath), diagnostics);
        } else {
            diagnosticCollection.delete(vscode.Uri.file(htmlFilePath));
        }

    } catch (e) {
        console.error(`Failed to load Jinja JSON schema: ${safeName}`, e);
    }
}


